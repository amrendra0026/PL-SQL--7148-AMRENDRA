SET SERVEROUTPUT ON;

DECLARE 

  CURSOR C_EMP IS
  SELECT ENAME, DEPTNO,DEPTNAME,BASICSAL FROM EMP
  ORDER BY BASICSAL DESC;

  V_ENAME EMP.ENAME%TYPE;
  V_DEPTNO EMP.DEPTNO%TYPE;
  V_DEPTNAME EMP.DEPTNAME%TYPE;
  V_BASICSAL EMP.BASICSAL%TYPE;

BEGIN 

  OPEN C_EMP;

  LOOP

  FETCH C_EMP INTO V_ENAME,V_DEPTNO,V_DEPTNAME,V_BASICSAL;

  EXIT WHEN C_EMP%ROWCOUNT>5;

  DBMS_OUTPUT.PUT_LINE('NAME:' || V_ENAME);
  DBMS_OUTPUT.PUT_LINE('DEPTNO:' || V_DEPTNO);
  DBMS_OUTPUT.PUT_LINE('DEPTNAME:' || V_DEPTNAME);
  DBMS_OUTPUT.PUT_LINE('BASICSAL:' || V_BASICSAL);


  END LOOP;

 CLOSE C_EMP;

END;
/
